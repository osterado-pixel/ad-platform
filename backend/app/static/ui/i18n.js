// ---------- Выбор языка ----------
function isLocale(value) {
  return LOCALES.includes(value);
}

function readLocaleCookie() {
  try {
    const m = document.cookie.match(/(?:^|;\s*)lang=([^;]+)/);
    return m && isLocale(m[1]) ? m[1] : null;
  } catch { return null; }  // cookie запрещены — язык браузера
}

// Как на сайте: выбор пользователя → язык браузера («de-AT» → de) → английский
function detectLocale() {
  const chosen = readLocaleCookie();
  if (chosen) return chosen;
  const browser = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ""])
    .map((tag) => String(tag).toLowerCase().split("-")[0])
    .find(isLocale);
  return browser || DEFAULT_LOCALE;
}

let locale = detectLocale();

// Запоминает выбор на год — тот же cookie читает сайт (src/proxy.ts)
function setLocale(next) {
  if (!isLocale(next)) return;
  locale = next;
  try {
    document.cookie = `${LOCALE_COOKIE}=${next}; path=/; max-age=31536000; samesite=lax`;
  } catch { /* cookie запрещены — выбор действует до перезагрузки */ }
  applyDocumentLocale();
}

function applyDocumentLocale() {
  document.documentElement.lang = locale;
}

// ---------- Перевод ----------
const pluralRules = {};
function pluralForm(forms, n) {
  pluralRules[locale] = pluralRules[locale] || new Intl.PluralRules(NUMBER_LOCALE[locale]);
  const form = pluralRules[locale].select(n);
  return forms[form] ?? forms.other;
}

function lookup(key, vars) {
  let msg = MESSAGES[locale][key] ?? MESSAGES[DEFAULT_LOCALE][key];
  if (msg === undefined) {
    console.warn(`i18n: no translation for "${key}"`);
    return key;
  }
  if (typeof msg === "object") msg = pluralForm(msg, Number(vars && vars.n));
  return msg;
}

/** Строка на текущем языке: t("ai.variant", { n: 2 }) → «Вариант 2». */
function t(key, vars) {
  return lookup(key, vars).replace(/\{(\w+)\}/g, (all, name) =>
    vars && vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : all);
}

/**
 * То же, но подстановки могут быть DOM-узлами (ссылка, жирный текст): возвращает массив
 * строк и узлов для h(). Текст по-прежнему вставляется только как текст — не как HTML.
 */
function tx(key, vars) {
  return lookup(key, vars).split(/\{(\w+)\}/).map((part, i) => {
    if (i % 2 === 0) return part;
    const value = vars && vars[part];
    return value === undefined || value === null ? `{${part}}` : value;
  }).filter((part) => part !== "");
}

// Числа и даты — в формате языка интерфейса
function numberLocale() {
  return NUMBER_LOCALE[locale];
}

